# --------------------------------------------------------------------------- parsing

def section_lines(md: str, heading: str) -> list[str]:
    """Return the body lines of the markdown section that starts with `heading`."""
    lines = md.splitlines()
    start = None
    for index, line in enumerate(lines):
        if line.startswith(heading):
            start = index
            break
    if start is None:
        raise SystemExit(f"[FAIL] artefact md: heading {heading!r} not found")
    end = len(lines)
    for index in range(start + 1, len(lines)):
        if lines[index].startswith("## "):
            end = index
            break
    return lines[start + 1:end]


def table_rows(lines: list[str]) -> list[dict[str, str]]:
    """Parse the first markdown table of `lines` into {header: cell} dicts."""
    header: list[str] | None = None
    rows: list[dict[str, str]] = []
    for line in lines:
        if not line.startswith("|"):
            if rows:
                break
            continue
        cells = [cell.strip() for cell in line.strip().strip("|").split("|")]
        if cells and all(cell and set(cell) <= {"-", ":"} for cell in cells):
            continue  # separator row
        if header is None:
            header = cells
            continue
        rows.append(dict(zip(header, cells)))
    if header is None or not rows:
        raise SystemExit("[FAIL] artefact md: expected a markdown table")
    return rows


def artifacts_table2_header(artifact: dict) -> list[str]:
    """Column names of the section-2 table (used to guard the positional reads)."""
    return list(artifact["table2"][0].keys())


def numeric_tokens(text: str) -> list[str]:
    """All number-like tokens of `text`, with thousands separators removed."""
    return [token.replace(",", "") for token in NUM_RE.findall(text)]


def reflow(text: str, limit: int = MAX_LINE) -> list[str]:
    """Split a paragraph into <=`limit`-character lines, breaking at sentence boundaries."""
    lines: list[str] = []
    current = ""
    for chunk in re.split(r"(?<=[。；])", text):
        while len(chunk) > limit:
            cut = chunk.rfind("，", 0, limit)
            cut = cut + 1 if cut > 0 else limit
            lines.append(current + chunk[:cut])
            current = ""
            chunk = chunk[cut:]
        if current and len(current) + len(chunk) > limit:
            lines.append(current)
            current = chunk
        else:
            current += chunk
    if current:
        lines.append(current)
    return lines


def tracker_knobs(script: Path) -> list[str]:
    """The 7 tracker knobs the pairing signature is built from (read from the eval script)."""
    text = script.read_text(encoding="utf-8")
    match = re.search(r"TRACKER_KNOBS\s*=\s*\(([^)]*)\)", text, re.S)
    if not match:
        raise SystemExit("[FAIL] TRACKER_KNOBS not found in the evaluation script")
    knobs = re.findall(r'"([^"]+)"', match.group(1))
    if not knobs:
        raise SystemExit("[FAIL] TRACKER_KNOBS is empty")
    return knobs


def derived_numbers(arm_json: Path) -> dict[str, float]:
    """Pooled-vs-mean-of-sequences demo, computed from the arm json (never hand-typed)."""
    data = json.loads(arm_json.read_text(encoding="utf-8"))
    per_sequence = data["per_sequence"]["3_jump_optimised"]["s1"]
    tp = sum(row["tp"] for row in per_sequence.values())
    fp = sum(row["fp"] for row in per_sequence.values())
    gt = sum(row["gt"] for row in per_sequence.values())
    precision = tp / (tp + fp)
    recall = tp / gt
    pooled = 2 * precision * recall / (precision + recall)
    mean_f1 = sum(row["f1_pct"] for row in per_sequence.values()) / len(per_sequence) / 100.0
    return {
        "n_sequences": float(len(per_sequence)),
        "pooled_f1": pooled,
        "mean_f1": mean_f1,
        "delta_pp": (pooled - mean_f1) * 100.0,
    }


def parse_artifact(md: str) -> dict:
    """Parse everything the section needs out of the artefact md."""
    sec1 = section_lines(md, "## 1.")
    sec2 = section_lines(md, "## 2.")
    sec2b = section_lines(md, "## 2b.")
    sec3 = section_lines(md, "## 3.")
    sec4 = section_lines(md, "## 4.")

    artifact: dict = {
        "table1": table_rows(sec1),
        "table2": table_rows(sec2),
        "table2b": table_rows(sec2b),
        "table3": table_rows(sec3),
        "scenario_notes": [line for line in sec2 if re.match(r"^- `s\d`", line)],
        "scenario_header": next(line for line in sec2 if line.startswith("情景语义")),
        "jump_summary": next(line for line in sec2 if line.startswith("⇒ `2b`")),
        "attribution": next(line for line in sec2 if "归因（假设，非因果证明）" in line),
    }

    verify = re.search(r"(\d+)/(\d+)\s*项通过", "\n".join(sec4))
    if not verify:
        raise SystemExit("[FAIL] artefact md: no 'N/N 项通过' line in section 4")
    artifact["verify_passed"] = int(verify.group(1))
    artifact["verify_total"] = int(verify.group(2))
    cadence = re.search(r"cadence 臂 \*\*(\d+/\d+)\*\*", "\n".join(sec4))
    artifact["cadence_arms"] = cadence.group(1) if cadence else "?"
    delivery = re.search(r"交付口径臂 \*\*(\d+)\*\*", "\n".join(sec4))
    artifact["delivery_arm_count"] = int(delivery.group(1)) if delivery else len(artifact["table1"])

    head2 = list(artifacts_table2_header(artifact))
    if head2[0] != "臂" or [column[:2] for column in head2[1:5]] != ["s1", "s2", "s3", "s4"]:
        raise SystemExit(f"[FAIL] artefact md: unexpected section-2 table shape {head2}")
    prose2b = "\n".join(sec2b)
    same = re.search(r"同源配对 (\d+) 例", prose2b)
    span = re.search(r"偏移区间 \*\*\[\+([\d.]+), \+([\d.]+)\]", prose2b)
    flips = re.search(r"\*\*(\d+) 例两口径判定相反\*\*", prose2b)
    if not (same and span and flips):
        raise SystemExit("[FAIL] artefact md: cannot parse the section 2b conclusion")
    artifact["prose_same_pairs"] = int(same.group(1))
    artifact["prose_offset_low"] = float(span.group(1))
    artifact["prose_offset_high"] = float(span.group(2))
    artifact["prose_flips"] = int(flips.group(1))
    artifact["conclusion_pair_line"] = next(line for line in sec2b if "同源配对" in line)
    artifact["conclusion_flip_line"] = next(line for line in sec2b if "例两口径判定相反" in line)
    artifact["note_mismatch"] = next(line for line in sec2b if line.startswith("⚠️ **异参行"))
    artifact["note_th045"] = next(line for line in sec2b if line.startswith("ℹ️ **表 2b 里没有出现的交付臂**"))
    artifact["note_offset_source"] = next(line for line in sec2b if line.startswith("⚠️ **偏移的来源要说准**"))
    artifact["note_trunc_redline"] = next(line for line in sec3 if line.startswith("⚠️ **这张表"))
    return artifact


# --------------------------------------------------------------------- the section

class Emitter:
    """Collects the lines of a section and the table cells that must be artefact-verbatim."""

    def __init__(self) -> None:
        self.lines: list[str] = []
        self.cells: list[str] = []

    def add(self, text: str = "") -> None:
        self.lines.append(text)

    def extend(self, texts: list[str]) -> None:
        self.lines.extend(texts)

    def header(self, cells: list[str]) -> None:
        self.lines.append("| " + " | ".join(cells) + " |")
        self.lines.append("| " + " | ".join("---" for _ in cells) + " |")

    def row(self, cells: list[str]) -> None:
        """A comparison-table row: every cell must be verbatim in the artefact md."""
        self.cells.extend(cells)
        self.lines.append("| " + " | ".join(cells) + " |")

    def ctx_row(self, cells: list[str]) -> None:
        """A context-table row (incident log): numbers are checked by the T2 token rule."""
        self.lines.append("| " + " | ".join(cells) + " |")


