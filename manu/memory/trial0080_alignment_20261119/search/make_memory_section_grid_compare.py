# ------------------------------------------------------------------- self-checks

def check(detailed: Emitter, compact: Emitter, artifact_md: str, canon: str,
          derived_tokens: set[str]) -> tuple[list[str], dict]:
    problems: list[str] = []
    artifact_tokens = set(numeric_tokens(artifact_md))
    canon_tokens = set(numeric_tokens(canon))
    allowed = artifact_tokens | canon_tokens | derived_tokens

    # T1 -- every comparison-table cell must be verbatim in the artefact md.
    cell_hit = 0
    for cell in detailed.cells + compact.cells:
        if cell in artifact_md:
            cell_hit += 1
        else:
            problems.append(f"T1 cell not verbatim in artefact md: {cell!r}")

    # T2 -- every number must have a declared source.
    num_hit = 0
    num_total = 0
    breakdown = {"artefact": 0, "derived": 0, "canonical_memory": 0}
    for name, emitter in (("detailed", detailed), ("compact", compact)):
        for token in sorted(set(numeric_tokens("\n".join(emitter.lines)))):
            num_total += 1
            if token in artifact_tokens:
                num_hit += 1
                breakdown["artefact"] += 1
            elif token in derived_tokens:
                num_hit += 1
                breakdown["derived"] += 1
            elif token in canon_tokens:
                num_hit += 1
                breakdown["canonical_memory"] += 1
            else:
                problems.append(f"T2 number {token!r} in {name} has no declared source")
    return problems, {"cell_hit": cell_hit, "cell_total": len(detailed.cells + compact.cells),
                       "num_hit": num_hit, "num_total": num_total, "breakdown": breakdown}


def check_lengths(lines: list[str], name: str) -> list[str]:
    return [f"T3 {name}:{index + 1} is {len(line)} chars (> {MAX_LINE}) :: {line}"
            for index, line in enumerate(lines) if len(line) > MAX_LINE]


def check_invariants(art: dict) -> list[str]:
    """T4 -- the table-2b statistics must agree with the artefact's own prose."""
    problems: list[str] = []
    t2b = art["table2b"]
    same = [row for row in t2b if row["检测侧同源"] == "✅"]
    offsets = [float(row["偏移"].lstrip("+")) for row in same]
    flips = [row for row in same if row["截断判定"] != row["交付判定"]]
    if len(same) != art["prose_same_pairs"]:
        problems.append(f"T4 same-source pairs: table {len(same)} vs prose {art['prose_same_pairs']}")
    if abs(min(offsets) - art["prose_offset_low"]) > 1e-9:
        problems.append(f"T4 offset low: table {min(offsets)} vs prose {art['prose_offset_low']}")
    if abs(max(offsets) - art["prose_offset_high"]) > 1e-9:
        problems.append(f"T4 offset high: table {max(offsets)} vs prose {art['prose_offset_high']}")
    if len(flips) != art["prose_flips"]:
        problems.append(f"T4 verdict flips: table {len(flips)} vs prose {art['prose_flips']}")
    return problems


def check_wording(lines: list[str], name: str) -> list[str]:
    """T5 -- the mechanism must be a hypothesis; the old causal wording must be gone."""
    problems: list[str] = []
    text = "\n".join(lines)
    if "归因（假设，非因果证明）" not in text:
        problems.append(f"T5 {name}: missing '归因（假设，非因果证明）'")
    for banned in ("不是参数差", "它假设「帧永远连续」", "崩不是参数差"):
        if banned in text:
            problems.append(f"T5 {name}: unconditional causal wording still present: {banned!r}")
    return problems


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out-dir", default=str(HERE), help="where the two section files are written")
    parser.add_argument("--dry-run", action="store_true", help="run the self-checks, write nothing")
    args = parser.parse_args()

    if not ARTIFACT_MD.exists():
        print(f"[FAIL] artefact md not found: {ARTIFACT_MD}")
        return 1
    artifact_md = ARTIFACT_MD.read_text(encoding="utf-8")
    art = parse_artifact(artifact_md)
    derived = derived_numbers(ARM_JSON)
    knobs = tracker_knobs(EVAL_SCRIPT)
    canon = MEMORY_MD.read_text(encoding="utf-8") + "\n" + MEMORY_COMPACT.read_text(encoding="utf-8")

    stamp = datetime.now().strftime("%Y-%m-%d")
    detailed = build_detailed(art, derived, stamp)
    build_table2b(detailed, art, knobs)
    build_shortlist(detailed, art)
    build_tail(detailed, art, stamp)
    build_provenance(detailed)
    compact = build_compact(art, derived, stamp)

    derived_tokens = {f"{derived['mean_f1']:.6f}", f"{derived['pooled_f1']:.6f}",
                      f"{derived['delta_pp']:.1f}", str(int(derived["n_sequences"])),
                      str(art["verify_passed"]), str(art["verify_total"]),
                      str(len(knobs)), str(len(art["table1"])), str(len(art["table3"]))}
    problems, stats = check(detailed, compact, artifact_md, canon, derived_tokens)
    problems += check_lengths(detailed.lines, "detailed")
    problems += check_lengths(compact.lines, "compact")
    problems += check_invariants(art)
    problems += check_wording(detailed.lines, "detailed")
    problems += check_wording(compact.lines, "compact")


    if problems:
        print(f"[FAIL] {len(problems)} problem(s) -- nothing written")
        for problem in problems[:40]:
            print(f"  - {problem}")
        return 1

    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    detailed_text = "\n".join(detailed.lines) + "\n"
    compact_text = "\n".join(compact.lines) + "\n"
    if args.dry_run:
        print("[DRY-RUN] nothing written")
    else:
        (out_dir / OUT_DETAILED).write_text(detailed_text, encoding="utf-8")
        (out_dir / OUT_COMPACT).write_text(compact_text, encoding="utf-8")
    print(f"[SELFCHECK] T1 cells verbatim in artefact md: {stats['cell_hit']}/{stats['cell_total']}")
    print(f"[SELFCHECK] T2 numbers with a declared source: {stats['num_hit']}/{stats['num_total']}"
          f"  (artefact md {stats['breakdown']['artefact']}"
          f" / arm-json derived {stats['breakdown']['derived']}"
          f" / canonical memory {stats['breakdown']['canonical_memory']})")
    print(f"[SELFCHECK] T3 lines <= {MAX_LINE} chars: detailed {len(detailed.lines)} lines, "
          f"compact {len(compact.lines)} lines")
    print(f"[SELFCHECK] T4 table-2b invariants agree with the artefact prose: "
          f"{art['prose_same_pairs']} same-source pairs, "
          f"[+{art['prose_offset_low']:.6f}, +{art['prose_offset_high']:.6f}], "
          f"{art['prose_flips']} verdict flips")
    print("[SELFCHECK] T5 mechanism stated as a hypothesis, old causal wording gone")
    print(f"[OUT] {out_dir / OUT_DETAILED}")
    print(f"[OUT] {out_dir / OUT_COMPACT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
