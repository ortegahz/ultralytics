#!/usr/bin/env python3
# ===========================================================================
# convert_yolov5_to_rknn.py -- re-quantize yolov5s.onnx into an RK3588 .rknn.
#
# Source model:
#   rknn-toolkit2/examples/onnx/yolov5/yolov5s.onnx
#   input  images : [1, 3, 640, 640]  float32  (NCHW)
#   outputs       : [1, 255, 80, 80] / [1, 255, 40, 40] / [1, 255, 20, 20]
#   (255 = 3 anchors x 85 channels -- the flattened NCHW head layout)
#
# NOTE this is a DIFFERENT output layout from the prebuilt
# rknpu2/examples/rknn_yolov5_demo/model/RK3588/yolov5s-640-640.rknn, which
# was built from `yolov5s_rm_transpose.onnx` and carries FIVE-dim heads
# [1, 3, 85, H, W]. Both layouts index identically under
#   (PROP_BOX_SIZE * a + c) * grid_len + i * grid_w + j
# because 3*85 == 255, so one decoder serves both -- see rknn_npu_smoke.cpp.
#
# Config deliberately mirrors two things, so the result is comparable to the
# shipped model rather than merely "some" rknn:
#   * rknn-toolkit2/examples/onnx/yolov5/test.py  -> mean 0, std 255
#   * rknpu2/examples/rknn_yolov5_demo's converter -> target_platform="rk3588"
#
# The calibration set is the single bus.jpg the SDK ships, i.e. the same image
# the demo is scored on. That is what the SDK's own scripts do, and it is noted
# here as a real limitation: one image is not a representative calibration set.
# It is kept as-is on purpose, because "same config as the reference" is the
# point of this exercise.
#
# init_runtime() is deliberately NOT called: it needs a board reachable over
# ADB/USB from this host, which we do not have. Conversion is pure host work;
# the resulting .rknn is validated on the board afterwards.
#
# Usage: python convert_yolov5_to_rknn.py [--out yolov5s_new.rknn]
# ===========================================================================
import argparse
import os
import shutil
import sys
import tempfile

from rknn.api import RKNN

SDK_RKNN = "/media/manu/1TB-Volume/rk3588/rk3588_sdk/EVM3588-A_20250815/02Linux软件资料/SDK&Image/SDK/evm3588_linux_sdk_v2.1.1.0"
SRC_DIR = os.path.join(SDK_RKNN, "external/rknn-toolkit2/examples/onnx/yolov5")
ONNX_MODEL = os.path.join(SRC_DIR, "yolov5s.onnx")
DATASET = os.path.join(SRC_DIR, "dataset.txt")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="yolov5s_from_onnx.rknn")
    ap.add_argument("--onnx", default=ONNX_MODEL)
    ap.add_argument("--dataset", default=DATASET)
    ap.add_argument("--calib-dir", default=None,
                    help="directory of images to use as the calibration set; "
                         "overrides --dataset and writes an absolute-path list")
    ap.add_argument("--calib-list", default=None,
                    help="text file of image paths (one per line, relative to --calib-dir "
                         "or absolute) to use as the calibration set")
    ap.add_argument("--no-quant", action="store_true",
                    help="build without quantization (fp16) -- comparison arm")
    args = ap.parse_args()

    for p in (args.onnx, args.dataset):
        if not os.path.isfile(p):
            sys.exit("[FATAL] missing %s" % p)
    print("[input ] %s (%.1f MB)" % (args.onnx, os.path.getsize(args.onnx) / 1e6))
    print("[out  ] %s" % args.out)
    print("[quant ] %s" % (not args.no_quant))

    # The SDK's dataset.txt lists a bare relative filename. Copy the whole
    # example dir to a scratch workspace and run there, so the relative path
    # resolves without ever writing into the SDK tree.
    work = tempfile.mkdtemp(prefix="rknn_conv_")
    try:
        for f in ("dataset.txt", "bus.jpg"):
            shutil.copy2(os.path.join(SRC_DIR, f), work)

        if args.calib_dir:
            imgs = []
            if args.calib_list:
                # Entries may be bare filenames, paths relative to the list's
                # own directory, or absolute. Try --calib-dir first (that is
                # where the images actually live when the list was generated by
                # `ls <dir> | sort`), then the list's directory, then as-is.
                list_dir = os.path.dirname(os.path.abspath(args.calib_list))
                for ln in open(args.calib_list):
                    ln = ln.strip()
                    if not ln:
                        continue
                    cands = []
                    if os.path.isabs(ln):
                        cands.append(ln)
                    else:
                        if args.calib_dir:
                            cands.append(os.path.join(args.calib_dir, ln))
                        cands.append(os.path.join(list_dir, ln))
                        cands.append(ln)
                    p = next((c for c in cands if os.path.isfile(c)), None)
                    if p is None:
                        sys.exit("[FATAL] calibration image missing: %s (tried %s)"
                                 % (ln, ", ".join(cands)))
                    imgs.append(p)
            else:
                imgs = sorted(os.path.join(args.calib_dir, f)
                              for f in os.listdir(args.calib_dir)
                              if f.lower().endswith((".jpg", ".jpeg", ".png")))
            if not imgs:
                sys.exit("[FATAL] no calibration images found")
            local_dataset = os.path.join(work, "dataset_abs.txt")
            with open(local_dataset, "w") as f:
                f.write("\n".join(imgs) + "\n")
            print("[calib ] %d images (abs paths)" % len(imgs))
            for p in imgs[:3]:
                print("         e.g. %s" % p)
            if len(imgs) > 3:
                print("         ... and %d more" % (len(imgs) - 3))
        else:
            local_dataset = os.path.join(work, "dataset.txt")
            print("[calib ] %s (SDK default: a single bus.jpg)" % args.dataset)

        os.chdir(work)

        rknn = RKNN(verbose=True)

        print("--> Config model")
        # mean 0 / std 255  =>  (x - 0) / 255 is what the NPU applies, so the
        # model consumes plain uint8 RGB, exactly like the shipped demo model.
        rknn.config(mean_values=[[0, 0, 0]],
                    std_values=[[255, 255, 255]],
                    target_platform="rk3588")
        print("done")

        print("--> Loading ONNX")
        ret = rknn.load_onnx(model=args.onnx)
        if ret != 0:
            sys.exit("[FATAL] load_onnx failed ret=%d" % ret)
        print("done")

        print("--> Building (this is the quantization step)")
        ret = rknn.build(do_quantization=not args.no_quant, dataset=local_dataset)
        if ret != 0:
            sys.exit("[FATAL] build failed ret=%d" % ret)
        print("done")

        print("--> Exporting")
        out_abs = os.path.abspath(args.out)
        ret = rknn.export_rknn(out_abs)
        if ret != 0:
            sys.exit("[FATAL] export_rknn failed ret=%d" % ret)
        print("done")

        rknn.release()

        if not os.path.isfile(out_abs):
            sys.exit("[FATAL] export reported success but %s is absent" % out_abs)
        size = os.path.getsize(out_abs)
        with open(out_abs, "rb") as f:
            head = f.read(8)
        if head[:4] != b"RKNN":
            sys.exit("[FATAL] %s does not start with the RKNN magic (got %r)"
                     % (out_abs, head))
        print()
        print("[OK] wrote %s  (%.2f MB, magic RKNN)" % (out_abs, size / 1e6))
    finally:
        os.chdir("/")
        shutil.rmtree(work, ignore_errors=True)


if __name__ == "__main__":
    main()