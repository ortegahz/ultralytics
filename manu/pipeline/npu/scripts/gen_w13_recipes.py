def floor_guard(recs):
    """🔴 **分辨率地板护栏**（§262 实测）：丢掉 maxΔ < 0.012 的配方。

    实测（台账 13:27，6056 个已合成臂）：maxΔ < 0.012 的 900 个臂，
    **nano 0/900 非零、nano4 几乎 0 非零** ⇒ 读数与基线**逐位相同** ⇒ **纯烧 GPU**。

    · 台账不可读 ⇒ **跳过护栏**（不因护栏本身把轴打死）。
    · 剪完条数不足 60 ⇒ **失败开放**（保留原样 + stderr 告警）
      —— 因为 `gen_watchdog.sh` 会在 60 s 内把「每通道 < 50 条」的生成器回滚成 `.good`。
    """
    try:
        led = WS.load_ledger()
        arms = led.get("arms") or {}
        fl = WS.Flattener(arms)
        base_vec = fl.flatten(led["baseline_v2"]["trial"], 1.0)
        if not base_vec:
            raise ValueError("baseline flatten empty")
        kept, dropped = WS.prune_below_floor(recs, base_vec, fl, WS.FLOOR_MAX_DELTA)
        kept = [rec for rec, _mx in kept]
    except Exception as exc:                                  # noqa: BLE001
        sys.stderr.write("[w13] floor_guard 跳过（%s）\n" % exc)
        return recs
    if len(kept) < 60:
        sys.stderr.write("[w13] floor_guard 剪完只剩 %d 条 < 60 ⇒ 失败开放保留原样\n" % len(kept))
        return recs
    sys.stderr.write("[w13] floor_guard: %d -> %d 条（剪掉 %d 条 maxΔ<%.3f）\n"
                     % (len(recs), len(kept), len(dropped), WS.FLOOR_MAX_DELTA))
    return kept


def main():
    chan = int(sys.argv[1]) if len(sys.argv) > 1 else 0
    rnd = int(sys.argv[2]) if len(sys.argv) > 2 else 0
    seen, out = set(), []
    for fn in AXES:
        for rec in fn(rnd):
            key = tuple(sorted(rec.split(",")))
            if key in seen:
                continue
            seen.add(key)
            out.append(rec)
    out = floor_guard(out)
    mine = [r for i, r in enumerate(out) if i % 4 == chan]
    sys.stderr.write("[w13] chan=%d total=%d mine=%d\n" % (chan, len(out), len(mine)))
    print(";".join(mine))


if __name__ == "__main__":
    main()
