#!/bin/bash
# 🟢 白天波 D2 · GPU3（2026-11-18）：三路汤 sb3 **bw 轴**（增益子 1100277@2 的权重档）
#   已知：1400001(.40/.40/.20) 官方门禁 T2_fp=3 ⇒ bw20 仍不够；
#         而 2 路族 w.70⇒3 / .75⇒2 ⇒ **增益子权重越高 T2_fp 越低** ⇒ 往 bw25/30/35/40 推。
#   家族口径：sb3 标签 = `sb3:<成员集合>:bw<增益子权重%>` ⇒ 每档 4 个不同拆分 ⇒ 每族 ≥4 票。
#   铁律：flock 互斥 + 起跑前查 MemAvailable（<40GB ⇒ 等 120s）。
set -u
REPO=/tmp/pycharm_project_10ae9e2e; PY=/home/huangzhe/anaconda3/envs/uav/bin/python
W=/mnt/data/siping/runs/npu20ms/nano_search; END="2026-11-19 07:30"
cd $REPO || exit 1
export PYTHONPATH=. OMP_NUM_THREADS=4 MKL_NUM_THREADS=4 OPENBLAS_NUM_THREADS=4 NUMEXPR_NUM_THREADS=4 NUMBA_NUM_THREADS=4
exec 9>"$W/.lock_d2_gpu3"
flock -n 9 || { echo "[$(date "+%F %T")] [D2-GPU3] 已有实例在跑 ⇒ 退出" >> "$W/d2_gpu3.log"; exit 0; }
log(){ echo "[$(date "+%F %T")] $*" >> $W/d2_gpu3.log; }
# 🟢🟢 2026-11-18 10:10 **PID 文件判活**（替代守望里的 `pgrep -f`）
#   坑：`pgrep -f "<脚本名>"` 会**匹配到任何提到该名字的 shell**（例如运维 ssh 命令本身）
#        ⇒ 守望误判「已在跑」⇒ 通道永远不重启。⇒ 改为脚本自己登记 PID + kill -0 验活。
PIDF=$W/.pid_synth3
echo $$ > "$PIDF"
trap 'rm -f "$PIDF"' EXIT

run3(){  # run3 <sid_base> <recipes> <logfile>
  timeout 7200 $PY -u manu/pipeline/npu/night_soup3.py --gpu 3 --sid-base "$1" --sid-span 200 \
    --max-gates 0 --mem-gate-gb 40 --deadline "$END" --recipes "$2" >> "$3" 2>&1
}
BW25="640001:5:0.375,1100296:1:0.375,1100277:2:0.25;640001:5:0.40,1100296:1:0.35,1100277:2:0.25;640001:5:0.35,1100296:1:0.40,1100277:2:0.25;640001:5:0.45,1100296:1:0.30,1100277:2:0.25"
BW30="640001:5:0.35,1100296:1:0.35,1100277:2:0.30;640001:5:0.40,1100296:1:0.30,1100277:2:0.30;640001:5:0.30,1100296:1:0.40,1100277:2:0.30;640001:5:0.45,1100296:1:0.25,1100277:2:0.30"
BW35="640001:5:0.325,1100296:1:0.325,1100277:2:0.35;640001:5:0.35,1100296:1:0.30,1100277:2:0.35;640001:5:0.30,1100296:1:0.35,1100277:2:0.35;640001:5:0.40,1100296:1:0.25,1100277:2:0.35"
BW40="640001:5:0.30,1100296:1:0.30,1100277:2:0.40;640001:5:0.35,1100296:1:0.25,1100277:2:0.40;640001:5:0.25,1100296:1:0.35,1100277:2:0.40;640001:5:0.40,1100296:1:0.20,1100277:2:0.40"
while :; do
  now=$(date +%s); end=$(date -d "$END" +%s)
  [ "$now" -lt "$end" ] || { log "[截止] $END ⇒ 退出"; break; }
  avail=$(awk '/MemAvailable/{printf "%d", $2/1024}' /proc/meminfo)
  if [ "${avail:-0}" -lt 40 ]; then log "[闸门] avail=${avail}GB < 40GB ⇒ 等 120s"; sleep 120; continue; fi
  log "[轮] D2-GPU3 段开始 avail=${avail}GB"
  run3 1520000 "$BW30" $W/soup3_d2_bw30.log
  run3 1521000 "$BW25" $W/soup3_d2_bw25.log
  run3 1522000 "$BW35" $W/soup3_d2_bw35.log
  run3 1523000 "$BW40" $W/soup3_d2_bw40.log
  # 🟢🟢 段5（09:50 新增，依据 bw30 实测 bench：640001=.30/1100296=.40/1100277=.30 ⇒ nano4 **.6604442**、
  #   F1 .8907770 ⇒ **三轴全过且 margin +0.34σ**，而 640001=.45 档 nano4 掉到 .6498 ⇒ **规律：640001 越轻 nano4 越好**）
  #   ⇒ 补「轻 640001 + 重 1100296(T3 锚) + 中等 1100277(T2fp 压)」区：bw25/bw30/bw35 各档
  #   ⇒ 每档 4 拆分 ⇒ 家族票数够（bw30 已有 4 个 ⇒ 本段再 +4）。
  run3 1532000 "640001:5:0.30,1100296:1:0.45,1100277:2:0.25;640001:5:0.25,1100296:1:0.50,1100277:2:0.25;640001:5:0.35,1100296:1:0.40,1100277:2:0.25;640001:5:0.20,1100296:1:0.55,1100277:2:0.25;640001:5:0.25,1100296:1:0.45,1100277:2:0.30;640001:5:0.20,1100296:1:0.50,1100277:2:0.30;640001:5:0.25,1100296:1:0.40,1100277:2:0.35;640001:5:0.20,1100296:1:0.45,1100277:2:0.35" $W/soup3_d2_light.log
  # 🟢🟢 段6（D3，10:30）：三路汤 **bw20~bw55 全档 × 5 拆分**（每档 5 成员 ⇒ 家族 n≥4 票数）
  #   拆分方式：固定增益子权重 bw，640001 ∈ {.15,.20,.25,.30,.35}，其余归 1100296@1（T3 锚）
  #   ⇒ 每档覆盖「640001 轻→重」的全谱系 ⇒ 同时抓 T1（要 640001 轻）与 nano4（要 640001 轻）。
  for BW in 20 25 30 35 40 45 50 55; do
    REC=$($PY -c "
bw=$BW/100
out=[]
for a in (0.15,0.20,0.25,0.30,0.35):
    b=round(1-a-bw,4)
    if b>=0.0499:
        out.append('640001:5:%.2f,1100296:1:%.2f,1100277:2:%.2f'%(a,b,bw))
print(';'.join(out))")
    [ -n "$REC" ] && run3 $((1533200 + (BW-20)*250)) "$REC" $W/soup3_d3_bw${BW}.log
  done
  log "[轮] D2-GPU3 段结束 ⇒ 睡 60s 再巡"
  sleep 60
done

